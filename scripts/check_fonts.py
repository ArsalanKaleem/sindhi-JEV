"""Phase 1: check that each font covers and shapes every Sindhi letter.

For each font and each required character:
  - cmap: the font maps the code point;
  - shaping: HarfBuzz shapes the letter isolated, initial, medial and final
    (joined with tatweel / beh) without producing .notdef (glyph id 0);
  - distinct: within each dot-confusion group, letters' isolated forms render
    to different bitmaps (a font that draws ٽ like ت would make labels wrong).

    python scripts/check_fonts.py --fonts fonts/*.ttf --out data/font_coverage.md
"""
import argparse
import glob
import hashlib
import json
import sys
from pathlib import Path

import uharfbuzz as hb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from sindhijev.alphabet import REQUIRED_CHARS  # noqa: E402
from sindhijev.render import Renderer  # noqa: E402

TATWEEL = "ـ"
NON_JOINERS = set("اآأدڌڏڊڍذرڙزوؤء۽")


def shape_gids(font, text):
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {})
    return [i.codepoint for i in buf.glyph_infos]


def contexts(c):
    ctx = {"isolated": c, "final": TATWEEL + c}
    if c not in NON_JOINERS:
        ctx["initial"] = c + TATWEEL
        ctx["medial"] = TATWEEL + c + TATWEEL
    return ctx


def check_font(path, groups):
    blob = hb.Blob.from_file_path(path)
    font = hb.Font(hb.Face(blob))
    cmap = hb.Face(blob).unicodes
    missing, notdef = [], []
    for c in REQUIRED_CHARS:
        if ord(c) not in cmap:
            missing.append(c)
            continue
        for form, text in contexts(c).items():
            if 0 in shape_gids(font, text):
                notdef.append(f"{c}:{form}")
    r = Renderer(path, size=48)
    same = []
    for g in groups:
        if g["kind"] == "encoding":
            continue
        seen = {}
        for m in g["members"]:
            img, _ = r.render(m["c"])
            h = hashlib.md5(img.tobytes() + bytes(img.shape)).hexdigest()
            if h in seen:
                same.append(f"{seen[h]}={m['c']}")
            else:
                seen[h] = m["c"]
    return missing, notdef, same


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", nargs="+", default=sorted(glob.glob(str(ROOT / "fonts" / "*.ttf"))))
    ap.add_argument("--confusion", default=str(ROOT / "data" / "confusion_set.json"))
    ap.add_argument("--out", default=str(ROOT / "data" / "font_coverage.md"))
    args = ap.parse_args()
    groups = json.load(open(args.confusion, encoding="utf-8"))["groups"]
    rows, ok_fonts = [], []
    for f in args.fonts:
        missing, notdef, same = check_font(f, groups)
        ok = not missing and not notdef and not same
        if ok:
            ok_fonts.append(Path(f).name)
        rows.append(f"| {Path(f).name} | {'PASS' if ok else 'FAIL'} | {' '.join(missing) or '-'} | "
                    f"{' '.join(notdef) or '-'} | {' '.join(same) or '-'} |")
        print(rows[-1])
    md = ["# Font coverage for Sindhi (generated by scripts/check_fonts.py)", "",
          f"Required characters ({len(REQUIRED_CHARS)}): {' '.join(REQUIRED_CHARS)}", "",
          "| Font | Result | Missing in cmap | .notdef after shaping | Group members drawn identically |",
          "|---|---|---|---|---|", *rows, "", f"Usable fonts: {', '.join(ok_fonts)}", ""]
    Path(args.out).write_text("\n".join(md), encoding="utf-8")


if __name__ == "__main__":
    main()
